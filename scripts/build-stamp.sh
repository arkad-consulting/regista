#!/bin/bash
# Writes Sources/RegistaCore/BuildStamp.generated.swift (gitignored) with the build id of the working tree, so the
# app, regista-mcp and regista-engine built next carry it (BuildStamp.swift explains the fallback "dev").
# The file is rewritten only when the id changes, so a no-op build stays a no-op.
# Prints one line: <id> <short sha> <dirty 0|1> <commit unix time>
#   id = <short sha>, or <short sha>-dirty.<6 hex of the uncommitted changes> when the tree is not clean
set -euo pipefail
cd "$(dirname "$0")/.."

sha="$(git rev-parse --short HEAD)"
ctime="$(git log -1 --format=%ct HEAD)"
dirty=0; id="$sha"
if [ -n "$(git status --porcelain)" ]; then
  dirty=1
  hash="$({ git diff HEAD --binary
            git ls-files -o --exclude-standard -z | while IFS= read -r -d '' f; do echo "$f"; cat "$f"; done
          } | shasum | cut -c1-6)"
  id="$sha-dirty.$hash"
fi

out=Sources/RegistaCore/BuildStamp.generated.swift
body="// Generated by scripts/build-stamp.sh — do not edit, do not commit.
extension BuildStampValues {
    static var id: String { \"$id\" }
    static var commitTime: Int? { $ctime }
}"
if [ ! -f "$out" ] || [ "$(cat "$out")" != "$body" ]; then printf '%s\n' "$body" > "$out"; fi
echo "$id $sha $dirty $ctime"
