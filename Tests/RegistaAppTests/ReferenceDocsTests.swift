// K1 (#7): the generated reference in docs/reference/ — every command (the registry the MCP server lists as tools), every
// keyboard shortcut (the catalog the menus and Impostazioni › Scorciatoie use), every engines.json key and every
// REGISTA_* environment variable the code reads. English only, never edited by hand.
//
// One generator: scripts/reference-docs.sh. It runs this suite with REGISTA_REFERENCE_OUT=<folder> (the test writes the
// files there) and scripts/engines.py docs (the engine table, from the engine manifest), then copies the folder to
// docs/reference/ — or, with --check, compares it with docs/reference/ and fails on any difference (the pre-commit hook).
// Without REGISTA_REFERENCE_OUT the test compares what it would write with docs/reference/ and names what is missing.

private let repoRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()

/// The entries of `<lang>.lproj/Localizable.strings`.
private func table(_ lang: String) -> [String: String] {
    let url = repoRoot.appendingPathComponent("Resources/Localization/\(lang).lproj/Localizable.strings")
    return (NSDictionary(contentsOf: url) as? [String: String]) ?? [:]
}

enum ReferenceDocs {
    static let header = "<!-- Generated by scripts/reference-docs.sh from the code. Do not edit by hand: change the code and run scripts/reference-docs.sh (the pre-commit hook fails when this file is stale). -->"

    /// File name → content of the files this generator writes (engines.md comes from scripts/engines.py).
    static func files(english en: [String: String]) -> [String: String] {
        ["commands.md": commands(en), "shortcuts.md": shortcuts(en), "settings.md": settings()]
    }

    // MARK: Commands

    /// Commands that change a brand kit (not the project) and that history.undo puts back: the ones whose source sets
    /// `ctx.kitChange` (read from Sources/RegistaCore/Commands, so a new kit command is found by itself).
    static var kitUndoable: Set<String> {
        let dir = repoRoot.appendingPathComponent("Sources/RegistaCore/Commands")
        let files = (try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: nil)) ?? []
        var out: Set<String> = []
        let start = try! NSRegularExpression(pattern: #"(?m)^(?:public )?enum \w+\s*:\s*Command\b"#)
        let idPattern = try! NSRegularExpression(pattern: #"static let id = "([^"]+)""#)
        for f in files where f.pathExtension == "swift" {
            guard let text = try? String(contentsOf: f, encoding: .utf8) else { continue }
            let ns = text as NSString
            // One block per `enum X: Command`, up to the next one.
            let starts = start.matches(in: text, range: NSRange(location: 0, length: ns.length)).map(\.range.location)
            for (i, s) in starts.enumerated() {
                let body = ns.substring(with: NSRange(location: s, length: (i + 1 < starts.count ? starts[i + 1] : ns.length) - s))
                guard body.contains("ctx.kitChange ="),
                      let m = idPattern.firstMatch(in: body, range: NSRange(body.startIndex..., in: body)),
                      let r = Range(m.range(at: 1), in: body) else { continue }
                out.insert(String(body[r]))
            }
        }
        return out
    }

    static func undo(_ d: CommandDescriptor, kit: Set<String>) -> String {
        if kit.contains(d.id) { return "yes — history.undo puts the brand kit back" }
        switch d.kind {
        case .edit: return "yes — one undo step"
        case .query: return "no — reads only"
        case .session: return "no — replaces or saves the project (opening or creating one clears the history)"
        case .history: return "– (moves through the undo history)"
        }
    }

    /// Table cell text: one line, pipes escaped.
    static func cell(_ s: String) -> String {
        s.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "|", with: "\\|")
    }

    static func type(_ t: ParamType) -> String {
        switch t {
        case .string: "string"
        case .integer: "integer"
        case .number: "number"
        case .boolean: "boolean"
        case .time: "seconds"
        case .object: "object"
        case .oneOf(let v): "one of " + v.map { "`\($0)`" }.joined(separator: ", ")
        case .array(let item): "array of " + type(item)
        }
    }

    /// The default a parameter's description states ("(default 18)", "default: the first audio track"), or "–".
    static func defaultValue(_ description: String) -> String {
        let re = try! NSRegularExpression(pattern: #"(?i)\bdefault(?:s to|:)?\s+([^);]+)"#)
        guard let m = re.firstMatch(in: description, range: NSRange(description.startIndex..., in: description)),
              let r = Range(m.range(at: 1), in: description) else { return "–" }
        var v = String(description[r]).trimmingCharacters(in: .whitespaces)
        if let dot = v.range(of: ". ") { v = String(v[..<dot.lowerBound]) }
        if v.hasSuffix(".") { v.removeLast() }
        return v.isEmpty ? "–" : v
    }

    /// The sentence of a summary that says what the command returns, or nil.
    static func returns(_ summary: String) -> String? {
        guard let r = summary.range(of: "Returns ", options: .backwards) else { return nil }
        return String(summary[r.lowerBound...]).trimmingCharacters(in: .whitespaces)
    }

    static func commands(_ en: [String: String]) -> String {
        let all = Engine().descriptors   // the descriptors MCPServer.listTools describes, sorted by id
        let kit = kitUndoable
        let groups = Dictionary(grouping: all) { String($0.id.split(separator: ".").first ?? "") }
        let order = groups.keys.sorted()
        var L: [String] = []
        let w = { (s: String) in L.append(s) }
        w("# Command reference")
        w("")
        w(header)
        w("")
        w("Every action in Regista is a command: the app's buttons and menus, `regista-engine exec` and Claude through MCP run the same ones. "
          + "This page lists the \(all.count) commands of the registry the MCP server describes its tools from.")
        w("")
        w("- **MCP tool**: the tool name Claude sees (the id with `_` for `.`). Commands marked human-only are not MCP tools: "
          + "the MCP server does not list them and refuses them; the person at the Mac runs them in the app (or with `regista-engine exec`).")
        w("- **Takes `project`**: every command but `project.new`, `project.open` and `project.list` also accepts `project`, "
          + "a tab id from `project.list` (\"tab-2\") or a `.regista` path; without it the command acts on the tab the user sees.")
        w("- **Undo**: whether `history.undo` can take the command back. A command that fails changes nothing.")
        w("- **Times** are seconds on the timeline and snap to the frame grid. **Default** is what the parameter's description says.")
        w("- **Title** is the command's name in the app's English interface (activity log, history, status bar).")
        w("")
        w("## Contents")
        w("")
        w(order.map { g in "[\(g)](#\(g.lowercased()))" }.joined(separator: " · "))
        w("")
        for g in order {
            w("## \(g)")
            w("")
            for d in groups[g]!.sorted(by: { $0.id < $1.id }) {
                let title = CommandTitles.key(d.id).flatMap { en[$0] } ?? "–"
                w("### `\(d.id)`")
                w("")
                w("**\(title)** · MCP tool: " + (d.humanOnly ? "none (human-only)" : "`\(MCPServer.toolName(d.id))`")
                  + " · undo: \(undo(d, kit: kit))" + (ProjectTarget.accepts(d.id) ? " · takes `project`" : ""))
                w("")
                w(d.summary)
                w("")
                if d.humanOnly {
                    w("Human-only: \(d.humanOnlyRefusal)")
                    w("")
                }
                if d.params.isEmpty {
                    w("No parameters.")
                } else {
                    w("| Parameter | Type | Required | Default | Description |")
                    w("|---|---|---|---|---|")
                    for p in d.params {
                        w("| `\(p.name)` | \(cell(type(p.type))) | \(p.required ? "yes" : "no") | \(p.required ? "–" : cell(defaultValue(p.description))) | \(cell(p.description)) |")
                    }
                }
                w("")
                w("Returns: " + (returns(d.summary).map { String($0.dropFirst("Returns ".count)) } ?? "see the description above."))
                w("")
            }
        }
        return L.joined(separator: "\n")
    }

    // MARK: Shortcuts

    /// "⇧⌘R", "Space": the keys as the menus show them, in English.
    static func keys(_ s: AppShortcut, _ en: [String: String]) -> String {
        var out = ""
        if s.modifiers.contains(.control) { out += "⌃" }
        if s.modifiers.contains(.option) { out += "⌥" }
        if s.modifiers.contains(.shift) { out += "⇧" }
        if s.modifiers.contains(.command) { out += "⌘" }
        return out + (s.key == .space ? en["Spazio"] ?? "Space" : AppShortcut.keyName(s.key))
    }

    static func shortcuts(_ en: [String: String]) -> String {
        var L: [String] = []
        let w = { (s: String) in L.append(s) }
        let all = AppShortcuts.all
        w("# Keyboard shortcuts")
        w("")
        w(header)
        w("")
        w("Every shortcut of the app, from the one catalog the menus take their keys from and Settings › Shortcuts lists "
          + "(\(all.count) entries). The editor's keys work when the editor has the focus and you are not typing; the "
          + "teleprompter's keys also come from pedals and presentation remotes.")
        w("")
        for g in AppShortcut.Group.allCases {
            let items = all.filter { $0.group == g }
            guard !items.isEmpty else { continue }
            w("## \(en[g.titleKey] ?? g.titleKey)")
            w("")
            w("| Keys | Action | Id |")
            w("|---|---|---|")
            for s in items {
                w("| \(cell(keys(s, en))) | \(cell(en[s.title] ?? s.title)) | `\(s.id)` |")
            }
            w("")
        }
        return L.joined(separator: "\n")
    }

