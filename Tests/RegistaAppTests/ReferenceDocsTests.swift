    /// The engines.json keys, in declaration order, with their default value ("nil" when unset by default).
    static var engineConfigKeys: [(key: String, value: String)] {
        Mirror(reflecting: EngineConfig()).children.compactMap { c in
            guard let label = c.label else { return nil }
            let m = Mirror(reflecting: c.value)
            if m.displayStyle == .optional { return (label, m.children.first.map { "\($0.value)" } ?? "nil") }
            return (label, "\(c.value)")
        }
    }

    /// Every REGISTA_* variable read with `environment["…"]` in Sources/.
    static var environmentVariables: [String] {
        let dir = repoRoot.appendingPathComponent("Sources")
        let files = FileManager.default.enumerator(at: dir, includingPropertiesForKeys: nil)!.compactMap { $0 as? URL }
            .filter { $0.pathExtension == "swift" }
        let re = try! NSRegularExpression(pattern: #"environment\["(REGISTA_[A-Z0-9_]+)"\]"#)
        var out: Set<String> = []
        for f in files {
            guard let text = try? String(contentsOf: f, encoding: .utf8) else { continue }
            for m in re.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
                if let r = Range(m.range(at: 1), in: text) { out.insert(String(text[r])) }
            }
        }
        return out.sorted()
    }

