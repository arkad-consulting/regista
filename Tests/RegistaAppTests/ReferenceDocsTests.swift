          + "`~`. A file that is not valid JSON is an error (engines.status reports it), not ignored. The default values "
          + "shown are those of this version.")
        w("")
        w("| Key | Default | What it is |")
        w("|---|---|---|")
        for (k, v) in engineConfigKeys {
            w("| `\(k)` | \(v == "nil" ? "not set" : "`\(cell(v))`") | \(cell(engineKeys[k] ?? "(no description)")) |")
        }
        w("")
        w("## Environment variables")
        w("")
        w("Read by the app, `regista-mcp` and `regista-engine` (developers and tests; nobody needs them for normal use).")
        w("")
        w("| Variable | What it does |")
        w("|---|---|")
        for v in environmentVariables { w("| `\(v)` | \(cell(environment[v] ?? "(no description)")) |") }
        w("")
        w("## The app's own choices")
        w("")
        w("The choices of the Settings window (folder, format of new projects, autosave, interface and spoken language, "
          + "forced tier, the brand kit accent) are set in the app; the forced tier is written into engines.json (`tier`), "
          + "the others are kept in the app's user defaults and are not meant to be edited by hand.")
        w("")
        return L.joined(separator: "\n")
    }

    /// The backticked ids of the items of a generated file (`### \`id\``, `| … | \`id\` |`, `| \`key\` |`).
    static func ids(_ text: String) -> Set<String> {
        let re = try! NSRegularExpression(pattern: #"^(?:### `([^`]+)`|\| `([^`]+)` \||\|.*\| `([A-Za-z0-9_.]+)` \|$)"#, options: .anchorsMatchLines)
        var out: Set<String> = []
        for m in re.matches(in: text, range: NSRange(text.startIndex..., in: text)) {
            for g in 1...3 { if let r = Range(m.range(at: g), in: text) { out.insert(String(text[r])) } }
        }
        return out
    }
