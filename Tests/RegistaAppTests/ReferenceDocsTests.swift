@Suite struct ReferenceDocsSuite {
    @Test func everyEngineKeyAndVariableIsDescribed() {
        let keys = ReferenceDocs.engineConfigKeys.map(\.key)
        #expect(Set(keys) == Set(ReferenceDocs.engineKeys.keys),
                "engines.json keys without a description in ReferenceDocs.engineKeys: \(Set(keys).subtracting(ReferenceDocs.engineKeys.keys).sorted()); described but gone: \(Set(ReferenceDocs.engineKeys.keys).subtracting(keys).sorted())")
        let vars = ReferenceDocs.environmentVariables
        #expect(!vars.isEmpty)
        #expect(Set(vars) == Set(ReferenceDocs.environment.keys),
                "REGISTA_* variables without a description in ReferenceDocs.environment: \(Set(vars).subtracting(ReferenceDocs.environment.keys).sorted()); described but no longer read: \(Set(ReferenceDocs.environment.keys).subtracting(vars).sorted())")
    }

    @Test func theKitCommandsAreFound() {
        let kit = ReferenceDocs.kitUndoable
        #expect(kit.isSuperset(of: ["brandkit.create", "brandkit.update", "brandkit.setLogo", "brandkit.delete"]), "\(kit.sorted())")
        #expect(!kit.contains("brandkit.list"))
    }

    /// With REGISTA_REFERENCE_OUT (scripts/reference-docs.sh): writes the files there. Without: docs/reference/ must be what
    /// this generator writes, and the failure names every command, shortcut or key missing from it.
    @Test func theReferenceDocsAreCurrent() throws {
        let files = ReferenceDocs.files(english: table("en"))
        if let out = ProcessInfo.processInfo.environment["REGISTA_REFERENCE_OUT"], !out.isEmpty {
            let dir = URL(fileURLWithPath: out, isDirectory: true)
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            for (name, text) in files { try (text + "\n").write(to: dir.appendingPathComponent(name), atomically: true, encoding: .utf8) }
            return
        }
        let docs = repoRoot.appendingPathComponent("docs/reference")
        for (name, text) in files.sorted(by: { $0.key < $1.key }) {
            let committed = (try? String(contentsOf: docs.appendingPathComponent(name), encoding: .utf8)) ?? ""
            let missing = ReferenceDocs.ids(text).subtracting(ReferenceDocs.ids(committed)).sorted()
            let gone = ReferenceDocs.ids(committed).subtracting(ReferenceDocs.ids(text)).sorted()
            let current = committed == text + "\n"
            #expect(current,
                    "docs/reference/\(name) is stale: run scripts/reference-docs.sh. Missing from it: \(missing.isEmpty ? "none" : missing.joined(separator: ", ")); no longer in the code: \(gone.isEmpty ? "none" : gone.joined(separator: ", "))")
        }
    }
}
